"""A list usd_deps generated, passed to isaac_sim_action, passes the launcher's check.

usd_deps_scene/ is a real package: its BUILD.bazel loads stage_deps.bzl and
passes STAGE_DEPS to an isaac_sim_action. Bazel analyses that action but does
not run it; its command line is written to a JSON file. The test runs what
would run in the container, the launcher with those arguments, under the real
usd-core and the stub Isaac Sim in fake_isaacsim/.
"""

import json
import os
import shutil
import subprocess
import sys
import unittest

from launcher_testing import LauncherTestCase, fake_isaacsim

USD_DEPS = os.path.abspath(os.environ["USD_DEPS"])
PACKAGE_DIR = os.path.dirname(os.path.abspath(os.environ["USD_DEPS_SCENE"]))
PACKAGE_PATH = "tests/isaac_sim/usd_deps_scene"
EXEC_ROOT_TOKEN = "__RULES_OMNIVERSE_EXEC_ROOT__"


def container_command():
    """The arguments the action gives python.sh: the launcher, its flags, --, the script."""
    with open(os.environ["USD_DEPS_ACTION_ARGV"]) as f:
        argv = json.load(f)
    # Runner flags come before the first --. Tests run in the runfiles root,
    # which holds the same relative paths as the execution root.
    command = argv[argv.index("--") + 1 :]
    return [arg.replace(EXEC_ROOT_TOKEN, os.getcwd()) for arg in command]


def flag_values(command, flag):
    return [command[i + 1] for i in range(len(command) - 1) if command[i] == flag]


def without_asset(command, asset):
    """command without the one --asset ASSET pair."""
    index = command.index(asset)
    return command[: index - 1] + command[index + 1 :]


class UsdDepsActionTest(LauncherTestCase):
    def setUp(self):
        super().setUp()
        self.ran = os.path.join(self.root, "script_ran")

    def environ(self):
        env = super().environ()
        env.pop("PYTHONSAFEPATH", None)
        # usd-core for the launcher's check, the stub isaacsim for the script.
        env["PYTHONPATH"] = os.pathsep.join([fake_isaacsim("FAKE_ISAACSIM")] + [p for p in sys.path if p])
        env["FAKE_KIT_EVENTS"] = self.events
        env["USD_DEPS_SCRIPT_RAN"] = self.ran
        return env

    def generate_in_a_copy(self):
        """Runs the tool on a copy of the package with no generated file; returns the generated bytes."""
        copy = os.path.join(self.root, "pkg")
        shutil.copytree(PACKAGE_DIR, copy)
        generated = os.path.join(copy, "stage_deps.bzl")
        os.remove(generated)
        env = dict(os.environ)
        env.pop("PYTHONPATH", None)
        env.pop("PYTHONSAFEPATH", None)
        result = subprocess.run(
            [USD_DEPS, os.path.join(copy, "stage.usda")], capture_output=True, text=True, env=env, timeout=60
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        with open(generated) as f:
            return f.read()

    def test_generated_list_passes_the_launchers_check(self):
        generated = self.generate_in_a_copy()
        with open(os.path.join(PACKAGE_DIR, "stage_deps.bzl")) as f:
            self.assertEqual(generated, f.read(), "the tool no longer writes the file the package loads")

        namespace = {}
        exec(generated, namespace)
        self.assertEqual(namespace["STAGE_DEPS"], ["props/chair.usda", "textures/wood.png"])

        command = container_command()
        self.assertEqual(
            flag_values(command, "--asset"),
            ["%s/%s" % (PACKAGE_PATH, path) for path in namespace["STAGE_DEPS"]],
        )

        result = self.run_python(command)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue(os.path.exists(self.ran), "the script did not run:\n%s" % result.stderr)
        self.assertEqual(self.kit_event_names(), ["start", "close"])

    # Precondition: the check above can fail. Without one entry of the list the
    # launcher refuses to start the script. If this fails, the setup is broken,
    # not the tool.
    def test_precondition_launcher_rejects_an_incomplete_list(self):
        command = without_asset(container_command(), "%s/textures/wood.png" % PACKAGE_PATH)
        result = self.run_python(command)
        self.assertNotEqual(result.returncode, 0, result.stderr)
        self.assertIn("wood.png", result.stderr)
        self.assertFalse(os.path.exists(self.ran), "script must not run when a dependency is undeclared")


if __name__ == "__main__":
    unittest.main()
