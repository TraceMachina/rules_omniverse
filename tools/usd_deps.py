#!/usr/bin/env python3
"""Generate the list of files a USD scene depends on, for isaac_sim_action's assets.

Usage: usd_deps [--check] SCENE...

The contract is docs/usd_deps.md.
"""

import argparse
import json
import os
import re
import sys

import isaac_sim_launcher

# One quoted string alone on its line, as this tool writes list entries.
_ENTRY = re.compile(r'^\s*"((?:[^"\\]|\\.)*)",?\s*$', re.MULTILINE)


def _parse(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="usd_deps",
        description="Write <scene>_deps.bzl beside each scene, listing the local files it depends on.",
    )
    parser.add_argument("--check", action="store_true", help="write nothing; fail if a generated file is out of date")
    parser.add_argument("scenes", metavar="SCENE", nargs="+", help="a USD file inside a Bazel package")
    return parser.parse_args(argv)


def _is_package(directory: str) -> bool:
    return any(os.path.isfile(os.path.join(directory, name)) for name in ("BUILD.bazel", "BUILD"))


def _package_of(scene: str) -> str | None:
    """The directory of the nearest BUILD file at or above scene, not looking above the workspace."""
    workspace = os.environ.get("BUILD_WORKSPACE_DIRECTORY")
    directory = os.path.dirname(scene)
    while not _is_package(directory):
        parent = os.path.dirname(directory)
        if directory == workspace or parent == directory:
            return None
        directory = parent
    return directory


def _package_relative(path: str, package: str) -> str | None:
    """path relative to package, or None when no label in package can name it."""
    relative = os.path.relpath(path, package)
    if relative.startswith(os.pardir + os.sep):
        return None
    parts = relative.split(os.sep)
    if any(_is_package(os.path.join(package, *parts[:depth])) for depth in range(1, len(parts))):
        return None
    return relative


def _listing(title: str, paths: set[str]) -> str:
    return "\n".join([title] + ["  " + path for path in sorted(paths)])


def _entries(scene: str, package: str) -> tuple[list[str], list[str]]:
    """Returns scene's entries, relative to package, and the errors that stop it being listed."""
    local, unresolved, online = isaac_sim_launcher.scene_dependencies(scene)
    for path in online:
        print("usd_deps: warning: online dependency is not listed: %s" % path, file=sys.stderr)

    entries, missing, outside = set(), set(unresolved), set()
    for path in local:
        if path == scene:
            continue
        if not os.path.exists(path):
            missing.add(path)
            continue
        relative = _package_relative(path, package)
        if relative is None:
            outside.add(path)
        else:
            entries.add(relative)

    errors = []
    if missing:
        errors.append(_listing("%s depends on files that do not exist:" % scene, missing))
    if outside:
        errors.append(_listing("%s depends on files outside its package, %s:" % (scene, package), outside))
    return sorted(entries), errors


def _bzl_bytes(scene_name: str, symbol: str, entries: list[str]) -> bytes:
    header = '"""Generated by usd_deps from %s. Do not edit."""\n\n' % scene_name
    if not entries:
        return (header + "%s = []\n" % symbol).encode("utf-8")
    lines = ["    %s,\n" % json.dumps(entry, ensure_ascii=False) for entry in entries]
    return (header + "%s = [\n%s]\n" % (symbol, "".join(lines))).encode("utf-8")


def _generate(scenes: list[str]) -> tuple[dict[str, tuple[bytes, list[str]]], list[str]]:
    """Returns each generated file's (bytes, entries) by path, and the errors of every scene."""
    generated, errors = {}, []
    seen = set()
    for scene in scenes:
        stem = os.path.splitext(os.path.basename(scene))[0]
        bzl = os.path.join(os.path.dirname(scene), stem + "_deps.bzl")
        symbol = re.sub("[^A-Z0-9_]", "_", stem.upper()) + "_DEPS"
        if not symbol[0].isalpha():
            errors.append("%s: a .bzl file cannot export the name %s" % (scene, symbol))
            continue
        if bzl in seen:
            errors.append("two scenes would write %s" % bzl)
        seen.add(bzl)
        if not os.path.isfile(scene):
            errors.append("scene does not exist: %s" % scene)
            continue
        package = _package_of(scene)
        if package is None:
            errors.append("%s is not in a package: no BUILD.bazel or BUILD file at or above it" % scene)
            continue
        entries, scene_errors = _entries(scene, package)
        errors += scene_errors
        generated[bzl] = (_bzl_bytes(os.path.basename(scene), symbol, entries), entries)
    return generated, errors


def _read(path: str) -> bytes | None:
    try:
        with open(path, "rb") as f:
            return f.read()
    except FileNotFoundError:
        return None


def _staleness(path: str, current: bytes | None, entries: list[str]) -> str:
    """Describes how the file at path differs from what would be generated."""
    wanted = {json.dumps(entry, ensure_ascii=False)[1:-1] for entry in entries}
    found = set(_ENTRY.findall((current or b"").decode("utf-8", errors="replace")))
    title = "%s is %s; run usd_deps on its scene" % (path, "missing" if current is None else "out of date")
    lines = ["  add: " + entry for entry in sorted(wanted - found)]
    lines += ["  remove: " + entry for entry in sorted(found - wanted)]
    return "\n".join([title] + lines)


def _print_errors(errors: list[str]) -> None:
    for error in errors:
        print("usd_deps: error: %s" % error, file=sys.stderr)


def main(argv: list[str]) -> int:
    options = _parse(argv)
    start = os.environ.get("BUILD_WORKING_DIRECTORY") or os.getcwd()
    scenes = [os.path.normpath(os.path.join(start, scene)) for scene in options.scenes]
    try:
        generated, errors = _generate(scenes)
    except ImportError:
        print("usd_deps: error: cannot import pxr from the usd-core package", file=sys.stderr)
        return 1
    if errors:
        _print_errors(errors)
        return 1

    currents = {path: _read(path) for path in generated}
    if options.check:
        stale = [
            _staleness(path, currents[path], entries)
            for path, (expected, entries) in generated.items()
            if currents[path] != expected
        ]
        _print_errors(stale)
        return 1 if stale else 0

    for path, (expected, _) in generated.items():
        if currents[path] != expected:
            with open(path, "wb") as f:
                f.write(expected)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
